local ns = {}
assert(loadfile("ForeverQuestChain/UI/Journal/Journal.lua"))("ForeverQuestChain", ns)

local journal = ns.Journal.New("MAGE")
assert(journal.route.tab == "search" and journal.route.page == "search")
journal:SelectTab("classes")
assert(journal.route.tab == "classes" and journal.route.page == "quests" and journal.route.key == "MAGE",
    "The Class Quests tab opens the player's class first")
journal:SelectTab("dungeons")
assert(journal.route.page == "locations" and journal.route.kind == "dungeons")
journal:OpenCategory("dungeons", 796)
assert(journal.route.tab == "dungeons" and journal.route.page == "quests" and journal.route.key == 796)
journal:OpenCategory("dungeons", 796, "rewards")
journal:OpenQuest()
assert(journal.route.tab == "dungeons" and journal.route.page == "chain",
    "A quest timeline stays inside its originating main tab")
journal:OpenQuest()
journal:Back()
assert(journal.route.page == "rewards" and journal.route.key == 796,
    "Selecting timeline steps must not overwrite the return destination")
journal:SelectTab("zones")
assert(journal.route.page == "locations")
journal:OpenCategory("zones", 37)
journal:SelectTab("dungeons")
assert(journal.route.page == "rewards" and journal.route.key == 796,
    "Main tabs remember their selected location and section independently")
journal:OpenLocations("dungeons")
assert(journal.route.page == "locations" and journal.route.kind == "dungeons")
journal:SelectTab("activeChains")
journal:OpenQuest()
journal:Back()
assert(journal.route.page == "activeChains", "Back from an active chain returns to its accordions")
journal:OpenCategory("classes", "DRUID")
assert(journal.route.tab == "classes" and journal.route.page == "quests", "Class links open the class tab")
journal:OpenQuest()
assert(journal.route.tab == "classes" and journal.route.page == "chain")
journal:Back()
assert(journal.route.page == "quests" and journal.route.key == "DRUID", "Back restores the selected class")
journal:OpenSearch()
assert(journal.route.tab == "search" and journal.route.page == "search")
journal:SelectTab("classes")
assert(journal.route.page == "quests" and journal.route.key == "DRUID", "Class selection survives tab switching")
journal:SelectTab("zones")
assert(journal.route.page == "quests" and journal.route.key == 37)
journal:OpenLocations("classes")
assert(journal.route.tab == "classes" and journal.route.key == "DRUID",
    "The Classes breadcrumb reopens the remembered class list")
print("journal navigation tests passed")
